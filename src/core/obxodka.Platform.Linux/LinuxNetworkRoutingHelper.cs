namespace obxodka.Platforms.Linux;

//вспомогательные функции разбора маршрутов linux, построения аргументов ip и бэкапа resolv.conf
public static class LinuxNetworkRoutingHelper
{
    public const string DefaultTunName = "obx0";
    public const string ResolvConfMarker = "# Generated by Obxodka CLI";
    public const string DefaultResolvConfPath = "/etc/resolv.conf";
    public const string DefaultResolvBackupPath = "/run/obxodka-resolv.conf.bak";

    //валидация имени сетевого интерфейса linux (максимум 15 символов, безопасный набор)
    public static bool IsValidInterfaceName(string? name) =>
        !string.IsNullOrWhiteSpace(name) &&
        name.Length <= 15 &&
        name.All(static ch => char.IsAsciiLetterOrDigit(ch) || ch is '_' or '-' or '.');

    //разбор вывода команды ip -4 route show default для определения шлюза и физического интерфейса
    public static bool TryParseDefaultRoute(string? ipRouteOutput, out string? gateway, out string interfaceName)
    {
        gateway = null;
        interfaceName = string.Empty;

        if (string.IsNullOrWhiteSpace(ipRouteOutput))
        {
            return false;
        }

        foreach (var rawLine in ipRouteOutput.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            if (!rawLine.StartsWith("default ", StringComparison.Ordinal))
            {
                continue;
            }

            var tokens = rawLine.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            string? foundGw = null;
            string? foundDev = null;

            for (var i = 1; i < tokens.Length - 1; i++)
            {
                if (tokens[i] == "via" && IPAddress.TryParse(tokens[i + 1], out var gwIp) && gwIp.AddressFamily == AddressFamily.InterNetwork)
                {
                    foundGw = gwIp.ToString();
                }
                else if (tokens[i] == "dev" && IsValidInterfaceName(tokens[i + 1]))
                {
                    foundDev = tokens[i + 1];
                }
            }

            if (!string.IsNullOrWhiteSpace(foundDev))
            {
                gateway = foundGw;
                interfaceName = foundDev;
                return true;
            }
        }

        return false;
    }

    //построение аргументов ip для /32 bypass-маршрута до vpn-сервера через физический интерфейс
    public static string[] BuildBypassRouteArgs(string action, string serverIp, string? gateway, string physicalInterface)
    {
        if (action is not ("replace" or "del"))
        {
            throw new ArgumentOutOfRangeException(nameof(action), action, "Ожидается replace или del.");
        }

        if (!IPAddress.TryParse(serverIp, out var parsed) || parsed.AddressFamily != AddressFamily.InterNetwork)
        {
            throw new ArgumentException($"Некорректный IPv4 адрес сервера: '{serverIp}'.", nameof(serverIp));
        }

        if (!IsValidInterfaceName(physicalInterface))
        {
            throw new ArgumentException($"Некорректный физический интерфейс: '{physicalInterface}'.", nameof(physicalInterface));
        }

        var hasGateway = !string.IsNullOrWhiteSpace(gateway) && IPAddress.TryParse(gateway, out var gwIp) &&
                         gwIp.AddressFamily == AddressFamily.InterNetwork;
        return hasGateway
            ? ["-4", "route", action, $"{parsed}/32", "via", IPAddress.Parse(gateway!).ToString(), "dev", physicalInterface]
            : ["-4", "route", action, $"{parsed}/32", "dev", physicalInterface];
    }

    //построение списка аргументов ip для перенаправления всего ipv4/ipv6 трафика в tun интерфейс
    public static IReadOnlyList<string[]> BuildTunnelRouteArgs(string action, string tunInterface, bool includeIpv6)
    {
        if (action is not ("replace" or "del"))
        {
            throw new ArgumentOutOfRangeException(nameof(action), action, "Ожидается replace или del.");
        }

        if (!IsValidInterfaceName(tunInterface))
        {
            throw new ArgumentException($"Некорректный TUN интерфейс: '{tunInterface}'.", nameof(tunInterface));
        }

        List<string[]> commands =
        [
            ["-4", "route", action, "0.0.0.0/1", "dev", tunInterface],
            ["-4", "route", action, "128.0.0.0/1", "dev", tunInterface]
        ];

        if (includeIpv6)
        {
            commands.Add(["-6", "route", action, "::/1", "dev", tunInterface]);
            commands.Add(["-6", "route", action, "8000::/1", "dev", tunInterface]);
        }

        return commands;
    }

    //формирование содержимого /etc/resolv.conf для защиты от утечек dns
    public static string BuildResolvConfContent(IReadOnlyList<string> dnsServers)
    {
        var sb = new StringBuilder();
        _ = sb.AppendLine(ResolvConfMarker);
        foreach (var ip in dnsServers
                     .Select(static dns => IPAddress.TryParse(dns, out var parsed) ? parsed : null)
                     .OfType<IPAddress>())
        {
            _ = sb.Append("nameserver ").AppendLine(ip.ToString());
        }

        _ = sb.AppendLine("options edns0 trust-ad");
        return sb.ToString();
    }

    //атомарный бэкап и подмена resolv.conf с защитой от повторной перезаписи бэкапа
    public static void ApplyResolvConfOverride(string resolvPath, string backupPath, IReadOnlyList<string> dnsServers)
    {
        var backupDir = Path.GetDirectoryName(backupPath);
        if (!string.IsNullOrWhiteSpace(backupDir))
        {
            _ = Directory.CreateDirectory(backupDir);
        }

        if (File.Exists(resolvPath) && !File.Exists(backupPath))
        {
            var current = File.ReadAllText(resolvPath);
            if (!current.StartsWith(ResolvConfMarker, StringComparison.Ordinal))
            {
                File.WriteAllText(backupPath, current, new UTF8Encoding(false));
            }
        }

        var tmpPath = $"{resolvPath}.obxodka.tmp";
        var content = BuildResolvConfContent(dnsServers);
        File.WriteAllText(tmpPath, content, new UTF8Encoding(false));
        File.Move(tmpPath, resolvPath, overwrite: true);
    }

    //восстановление оригинального resolv.conf из бэкапа
    public static bool RestoreResolvConfBackup(string resolvPath, string backupPath)
    {
        if (!File.Exists(backupPath))
        {
            return false;
        }

        var original = File.ReadAllText(backupPath);
        var tmpPath = $"{resolvPath}.obxodka.restore.tmp";
        File.WriteAllText(tmpPath, original, new UTF8Encoding(false));
        File.Move(tmpPath, resolvPath, overwrite: true);
        File.Delete(backupPath);
        return true;
    }

    //безопасный запуск системной утилиты без shell-интерпретации
    public static async Task<(int ExitCode, string StdOut, string StdErr)> RunProcessAsync(
        string fileName,
        IReadOnlyList<string> arguments,
        CancellationToken ct)
    {
        using var process = new Process();
        process.StartInfo = new ProcessStartInfo
        {
            FileName = fileName,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            CreateNoWindow = true
        };

        foreach (var arg in arguments)
        {
            process.StartInfo.ArgumentList.Add(arg);
        }

        if (!process.Start())
        {
            return (-1, string.Empty, $"Не удалось запустить процесс '{fileName}'.");
        }

        var stdoutTask = process.StandardOutput.ReadToEndAsync(ct);
        var stderrTask = process.StandardError.ReadToEndAsync(ct);
        await process.WaitForExitAsync(ct).ConfigureAwait(false);
        var stdout = await stdoutTask.ConfigureAwait(false);
        var stderr = await stderrTask.ConfigureAwait(false);
        return (process.ExitCode, stdout, stderr);
    }
}
